# ---------------------------------------------------------------- 7. a rank-1 update on a 4x4 matrix
def rank1():
    T = LM['toy']
    b = [text(20, 24, 'A rank-1 update: 8 trained numbers make a 4 x 4 change (ch5_lora_math.py)', 't-title')]
    cell = 44
    def grid(x0, y0, M, title):
        g = [text(x0 + len(M[0]) * cell / 2, y0 - 10, title, 't-note', 'middle')]
        mx = max(abs(v) for r in M for v in r) or 1
        for i, r in enumerate(M):
            for j, v in enumerate(r):
                cls = 's1' if v >= 0 else 's2'
                g.append(f'<rect class="{cls}" x="{x0 + j * cell + 1}" y="{y0 + i * cell + 1}" width="{cell - 2}" height="{cell - 2}" rx="3" style="fill-opacity:{0.15 + 0.6 * abs(v) / mx:.2f}"/>')
                g.append(text(x0 + j * cell + cell / 2, y0 + i * cell + cell / 2 + 4, f'{v:.2f}', 't-cell', 'middle'))
        return g
    b += grid(40, 70, [[v] for v in T['B']], 'B (4 x 1)')
    b.append(text(110, 160, 'x', 't-big', 'middle'))
    b += grid(130, 136, [T['A']], 'A (1 x 4)')
