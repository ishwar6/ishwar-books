# ---------------------------------------------------------------- 4. per-token losses before and after
def pertoken():
    if not TPL or 'lora' not in TPL:
        return None
    runs = [('base model', TPL['base'], 's1'), ('plain LoRA', TPL['lora_plain'], 's2'), ('LoRA + 2 token rows', TPL['lora'], 's3')]
    base = TPL['base']['rows']
    b = [text(20, 24, 'Loss at every learned token of one example, before and after fine-tuning (ch5_template.py)', 't-title')]
    n = len(base)
    cw = 700 / n
    top, H = 56, 200
    vmax = 15
    Y = lambda v: top + H - min(v, vmax) / vmax * H
    for t in range(0, vmax + 1, 5):
        b += [f'<line class="grid" x1="60" y1="{Y(t):.1f}" x2="770" y2="{Y(t):.1f}"/>', text(52, Y(t) + 4, str(t), 't-tick', 'end')]
    bw = cw * 0.27
    for i in range(n):
        x = 66 + i * cw
        for k, (name, R, cls) in enumerate(runs):
            p, v = R['rows'][i]
            b.append(f'<g class="mark"><title>{esc(p)}: {name} {v:.3f}</title><rect class="{cls}" x="{x + k * (bw + 1):.1f}" y="{Y(v):.1f}" width="{bw:.1f}" height="{max(0.8, top + H - Y(v)):.1f}" rx="2"/></g>')
        lab = base[i][0].replace('\n', '\u21b5').strip() or '\u2423'
        cx = x + cw * 0.45
        b.append(text(cx, top + H + 12, lab, 't-tick', 'end', f' transform="rotate(-45 {cx:.1f} {top + H + 12})"'))
    last = 66 + (n - 1) * cw
    for k, (name, R, cls) in enumerate(runs):
        v = R['rows'][-1][1]
        b.append(text(last + k * (bw + 1) + bw / 2, Y(v) - 5, f'{v:.2f}' if v > 0.1 else f'{v:.3f}', 't-tick', 'middle'))
    b.append(text(60, top - 14, 'loss in nats (-log p of the true token)', 't-muted'))
    yy = top + H + 96
    for k, (name, R, cls) in enumerate(runs):
        b += [f'<rect class="{cls}" x="60" y="{yy - 10 + 20 * k}" width="10" height="10" rx="2"/>',
              text(76, yy + 20 * k, f'{name}: mean over the 12 tokens {R["masked"]:.3f}, without <|im_end|> {R["no_end"]:.3f}', 't-tick')]
    return svg(790, yy + 66, 'Bar chart of the loss at each learned token of one example for the base model, plain LoRA and LoRA with the two token rows trained.', b)


F['ch5_pertoken'] = pertoken()


# ---------------------------------------------------------------- 5. padding vs packing
def packing():
    if not TPL or 'bucket_slots' not in TPL['pack']:
        return None
    P = TPL['pack']
    b = [text(20, 24, f'Padding or packing the {P["real"]:,} real tokens of our 1,000 training examples (ch5_template.py)', 't-title')]
    W = 560
    mx = max(P['pad_slots'], P['bucket_slots'])
    bars = [('random batches of 8, padded to the longest', P['pad_slots'], 's2'),
            ('the same, rounded up to a multiple of 128 (our run)', P['bucket_slots'], 's4'),
            ('packed into full rows of 384', P['packed_slots'], 's3')]
    for i, (name, slots, cls) in enumerate(bars):
        y = 56 + i * 58
        full = W * slots / mx
        real = W * P['real'] / mx
        b += [text(20, y - 8, f'{name}: {slots:,} slots, {1 - P["real"] / slots:.0%} padding', 't-tick')]
        b += [f'<rect class="{cls}" x="20" y="{y}" width="{real:.1f}" height="24" rx="3"/>', box(20 + real, y, max(0.5, full - real), 24, 'box-ghost', 3)]
    b += para(20, 56 + 3 * 58 + 6, ['Filled: real tokens. Dashed: padding, which costs compute and teaches nothing.',
                                    'Packing puts several examples in one row; the attention or at least the loss must then be kept per example.'], 't-muted')
    return svg(760, 56 + 3 * 58 + 44, 'Three bars comparing token slots used by padded batches, padded batches rounded to 128, and packing.', b)


F['ch5_packing'] = packing()


