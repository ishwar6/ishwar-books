# ---------------------------------------------------------------- 10. the SFT loss curves
def loss_curve():
    if not LORA:
        return None
    ser = [('train loss', LORA['step'], LORA['loss'], 'l1', 's1'), ('held-out: LoRA + rows', LORA['val_step'], LORA['val'], 'l3', 's3')]
    if PLAIN:
        ser.append(('held-out: plain LoRA', PLAIN['val_step'], PLAIN['val'], 'l2', 's2'))
    if FULL:
        ser.append(('held-out: full FT', FULL['val_step'], FULL['val'], 'l4', 's4'))
    S = LORA['step'][-1]
    lo = min(min(LORA['loss']), min(LORA['val'])) - 0.1
    hi = max(max(LORA['loss']), max(LORA['val'])) + 0.1
    lo, hi = math.floor(lo * 10) / 10, math.ceil(hi * 10) / 10
    ticks = [round(lo + k * 0.2, 1) for k in range(int((hi - lo) / 0.2) + 1)]
    b, X, Y = chart(80, 64, 520, 230, ser, (0, S), (lo, hi), [0, S // 4, S // 2, 3 * S // 4, S], ticks, fx=lambda v: f'{int(v)}',
                    fy=lambda v: f'{v:.1f}', xlabel='training step (8 examples per step)', ylabel='loss per reply token (nats)')
    b = [p for p in b if not ('circle class="s1' in p)]
    b.insert(0, text(20, 24, 'SFT of Qwen2.5-0.5B on 1,000 Alpaca examples: loss per reply token', 't-title'))
    if REF:
        ins = REF['Qwen/Qwen2.5-0.5B-Instruct']['heldout']
        b.append(f'<line class="base-line" x1="80" y1="{Y(ins):.1f}" x2="600" y2="{Y(ins):.1f}"/>')
        b.append(text(80, 362, f'dashed line: Qwen2.5-0.5B-Instruct on the same held-out examples, {ins:.3f}', 't-muted'))
    return svg(800, 372, 'Training loss and held-out loss over the fine-tuning steps.', b)


F['ch5_loss'] = loss_curve()


