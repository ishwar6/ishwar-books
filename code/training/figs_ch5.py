    b += grid(360, 70, T['dW'], 'Delta W = B A (4 x 4)')
    b += para(560, 90, ['Every row of Delta W is a multiple', 'of the same row A; every column', 'is a multiple of the same column B.',
                        '', '16 numbers, 8 parameters, rank 1.', 'At rank r: r x (d_in + d_out)', 'parameters instead of d_in x d_out.'], 't-tick')
    return svg(800, 270, 'A worked rank-1 update: a column B times a row A gives a 4 by 4 matrix whose rows are all multiples of A.', b)


